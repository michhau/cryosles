MODULE SP_SC1

USE PARAM,ONLY:LD,NY,NZ,MODEL
USE TYPES

IMPLICIT NONE

REAL(RPREC),DIMENSION(LD,NY) :: LBC_SC1,        &          !DIRICHLET/FLUX BC
                                UBC_SC1

REAL(RPREC),DIMENSION(:,:,:),ALLOCATABLE :: EPSI_SC1


REAL(RPREC),DIMENSION(:,:,:),ALLOCATABLE ::  SC1,                          &
                                      RHS_SC1,RHSF_SC1,             &
                                      DSC1DZ,DSC1DX,DSC1DY,         &
                                      TXSC1,TYSC1,TZSC1,            &
                                      NU_SC1,BETA_SC1,SC1_LAG
REAL(RPREC),DIMENSION(:,:,:),ALLOCATABLE ::  DS_OPT2_SC1

REAL(RPREC),DIMENSION(:,:),ALLOCATABLE :: SC1_STAR,PHI_H,PSI_H
REAL(RPREC),DIMENSION(:,:),ALLOCATABLE :: LBC_SC1_ZO
!law of the wall models
REAL(RPREC),DIMENSION(LD,NY) :: DSC1DZMOD,TZSC1MOD
! Vertical SGS flux of SC1 at specific grid node for eddy covariance sampling output
REAL(RPREC) :: ATTZ_EDDY_COV


CONTAINS

! ALLOCATION
subroutine allocTemperature()

print*,'allocation scalars'

ALLOCATE(EPSI_SC1(LD,NY,0:NZ))
ALLOCATE(SC1(LD,NY,0:NZ))
ALLOCATE(DSC1DX(LD,NY,0:NZ))
ALLOCATE(DSC1DY(LD,NY,0:NZ))
ALLOCATE(DSC1DZ(LD,NY,0:NZ))
ALLOCATE(RHS_SC1(LD,NY,0:NZ))
ALLOCATE(RHSF_SC1(LD,NY,0:NZ))
ALLOCATE(TXSC1(LD,NY,0:NZ))
ALLOCATE(TYSC1(LD,NY,0:NZ))
ALLOCATE(TZSC1(LD,NY,0:NZ))
ALLOCATE(NU_SC1(LD,NY,0:NZ))
ALLOCATE(BETA_SC1(LD,NY,0:NZ))
ALLOCATE(SC1_LAG(LD,NY,0:NZ))
ALLOCATE(DS_OPT2_SC1(LD,NY,NZ))

ALLOCATE(SC1_STAR(LD,NY))
ALLOCATE(PSI_H(LD,NY))
ALLOCATE(PHI_H(LD,NY))
ALLOCATE(LBC_SC1_ZO(LD,NY))

end subroutine allocTemperature


! DEALLOCATION
subroutine deAllocTemperature()

DEALLOCATE(EPSI_SC1)
DEALLOCATE(SC1)
DEALLOCATE(DSC1DX)
DEALLOCATE(DSC1DY)
DEALLOCATE(DSC1DZ)
DEALLOCATE(RHS_SC1)
DEALLOCATE(RHSF_SC1)
DEALLOCATE(TXSC1)
DEALLOCATE(TYSC1)
DEALLOCATE(TZSC1)
DEALLOCATE(NU_SC1)
DEALLOCATE(BETA_SC1)
DEALLOCATE(SC1_LAG)
DEALLOCATE(DS_OPT2_SC1)
DEALLOCATE(SC1_STAR)
DEALLOCATE(PSI_H)
DEALLOCATE(PHI_H)
DEALLOCATE(LBC_SC1_ZO)

end subroutine deAllocTemperature



END MODULE SP_SC1
