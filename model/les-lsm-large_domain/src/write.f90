END SUBROUTINE WRITE_I


!###################################################################
SUBROUTINE WRITE_MAT_ASCII(PATH,VAR,SVAR,ST,POS,JT)

IMPLICIT NONE

REAL(RPREC),DIMENSION(:,:),INTENT(IN) :: VAR
CHARACTER(*),INTENT(IN) :: PATH,SVAR,ST,POS
CHARACTER(256) :: FNAME
INTEGER,OPTIONAL,INTENT(IN) :: JT
INTEGER :: I,J,N1,N2

N1=SIZE(VAR(:,1))
N2=SIZE(VAR(1,:))

!FILENAME
IF(PRESENT(JT))THEN
   WRITE(FNAME,'(A,I6.6,A)') TRIM(PATH)//TRIM(SVAR)//'_',JT,'.dat'
ELSE
   WRITE(FNAME,'(A)') TRIM(PATH)//TRIM(SVAR)//'.dat'
ENDIF

!WRITE TO FILE
OPEN(111,FILE=TRIM(FNAME),STATUS=TRIM(ST),POSITION=TRIM(POS))
DO J=1,SIZE(VAR(1,:))
   WRITE(111,10) VAR(:,J)
ENDDO
CLOSE(111)

10 FORMAT(2048(F24.12))

END SUBROUTINE WRITE_MAT_ASCII


SUBROUTINE WRITE_MAT_BIN(PATH,VAR,SVAR,IND,JT)

IMPLICIT NONE

REAL(RPREC),DIMENSION(:,:),INTENT(IN) :: VAR
CHARACTER(*),INTENT(IN) :: PATH,SVAR
CHARACTER(256) :: FNAME
INTEGER,OPTIONAL,INTENT(IN) :: JT,IND
INTEGER :: N1,N2

N1=SIZE(VAR(:,1))
N2=SIZE(VAR(1,:))

!FILENAME
IF(PRESENT(JT))THEN
   WRITE(FNAME,'(A,I6.6,A)') TRIM(PATH)//TRIM(SVAR)//'_',JT,'.dat'
ELSE
   WRITE(FNAME,'(A)') TRIM(PATH)//TRIM(SVAR)//'.dat'
ENDIF

!WRITE TO FILE
OPEN(111,FILE=TRIM(FNAME),STATUS='UNKNOWN',ACCESS='DIRECT',RECL=4*N1*N2)
WRITE(111,REC=IND) REAL(VAR(1:N1,1:N2))
CLOSE(111)

END SUBROUTINE WRITE_MAT_BIN


END MODULE WRITE
