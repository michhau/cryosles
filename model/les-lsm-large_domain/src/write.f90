MODULE WRITE

USE TYPES

INTERFACE FWRITE
   MODULE PROCEDURE WRITE_F,WRITE_I,WRITE_MAT_ASCII,WRITE_MAT_BIN
END INTERFACE

CONTAINS

!###################################################################
SUBROUTINE WRITE_F(PATH,VAR,SVAR,ST,POS,JT)

IMPLICIT NONE

REAL(RPREC),INTENT(IN) :: VAR
CHARACTER(*),INTENT(IN) :: PATH,SVAR,ST,POS
CHARACTER(256) :: FNAME
INTEGER,INTENT(IN),OPTIONAL :: JT
INTEGER :: I,J

IF(PRESENT(JT))THEN
   WRITE(FNAME,'(A,I6.6,A)') TRIM(PATH)//TRIM(SVAR)//'_',JT,'.dat'
   OPEN(111,FILE=TRIM(FNAME),STATUS=TRIM(ST),POSITION=TRIM(POS))
   WRITE(111,10) VAR
   CLOSE(111)
ELSE
   WRITE(FNAME,'(A)') TRIM(PATH)//TRIM(SVAR)//'.dat'
   OPEN(111,FILE=TRIM(FNAME),STATUS=TRIM(ST),POSITION=TRIM(POS))
   WRITE(111,10) VAR
   CLOSE(111)
ENDIF

10 FORMAT(2048(F24.12))

END SUBROUTINE WRITE_F


!###################################################################
